def inline(text: str) -> str:
    """Inline markdown -> HTML (escape first, then spans)."""
    out = html_mod.escape(text, quote=False)
    out = re.sub(r"`([^`]+)`", r"<code>\1</code>", out)
    out = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", out)

    def link(m):
        label, url = m.group(1), m.group(2)
        base, separator, fragment = url.partition("#")
        for page_name, source_path in SOURCE_PATHS.items():
            relative_source = source_path.relative_to(DOCS).as_posix()
            if base in {relative_source, f"docs/{relative_source}"}:
                url = page_name + ".html"
                if separator:
                    url += "#" + fragment
                break
        else:
            rewritten = re.sub(r"^(?:docs/)?([\w-]+)\.md$", r"\1.html", base)
            if rewritten != base:
                url = rewritten
                if separator:
                    url += "#" + fragment
        return f'<a href="{url}">{label}</a>'

    return re.sub(r"\[([^\]]+)\]\(([^)]+)\)", link, out)


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


# ── build-time syntax highlighting (bash / json / env) ──────────
def _esc(s: str) -> str:
    return html_mod.escape(s, quote=False)


_BASH_TOKEN = re.compile(r"""('[^']*'|"[^"]*"|\$\{[^}]*\}|\$\w+|#.*$|\s+|[^\s'"$#]+)""")
_BASH_JOINERS = {"&&", "||", "|", ";"}


def _hl_bash(code: str) -> str:
    out = []
    for ln in code.split("\n"):
        if re.match(r"^\s*#", ln):
            out.append(f'<span class="hl-c">{_esc(ln)}</span>')
            continue
        parts, new_cmd, pos = [], True, 0
        for m in _BASH_TOKEN.finditer(ln):
            if m.start() > pos:
                parts.append(_esc(ln[pos:m.start()]))
            pos = m.end()
            tok = m.group(0)
            if tok.startswith(("'", '"')):
                parts.append(f'<span class="hl-s">{_esc(tok)}</span>')
                new_cmd = False
            elif tok.startswith("$"):
                parts.append(f'<span class="hl-v">{_esc(tok)}</span>')
                new_cmd = False
            elif tok.startswith("#"):
                parts.append(f'<span class="hl-c">{_esc(tok)}</span>')
            elif tok.isspace():
                parts.append(tok)
            else:
                if new_cmd:
                    parts.append(f'<span class="hl-cmd">{_esc(tok)}</span>')
                    new_cmd = False
                elif tok.startswith("-"):
                    parts.append(f'<span class="hl-f">{_esc(tok)}</span>')
                else:
                    parts.append(_esc(tok))
                if tok in _BASH_JOINERS:
                    new_cmd = True
        if pos < len(ln):
            parts.append(_esc(ln[pos:]))
        out.append("".join(parts))
    return "\n".join(out)


_JSON_TOKEN = re.compile(r'("(?:\\.|[^"\\])*")(\s*:)?|(\b(?:true|false|null)\b|-?\d+(?:\.\d+)?)')


def _hl_json(code: str) -> str:
    out, pos = [], 0
    for m in _JSON_TOKEN.finditer(code):
        out.append(_esc(code[pos:m.start()]))
        if m.group(1) and m.group(2):
            out.append(f'<span class="hl-k">{_esc(m.group(1))}</span>{_esc(m.group(2))}')
        elif m.group(1):
            out.append(f'<span class="hl-s">{_esc(m.group(1))}</span>')
        else:
            out.append(f'<span class="hl-n">{_esc(m.group(3))}</span>')
        pos = m.end()
    out.append(_esc(code[pos:]))
    return "".join(out)


def _hl_env(code: str) -> str:
    out = []
    for ln in code.split("\n"):
        if re.match(r"^\s*#", ln):
            out.append(f'<span class="hl-c">{_esc(ln)}</span>')
            continue
        m = re.match(r"^([A-Za-z_][A-Za-z0-9_]*)(=)(.*)$", ln)
        if m:
            val = m.group(3)
            val_html = (f'<span class="hl-s">{_esc(val)}</span>'
                        if val.startswith(("'", '"')) else _esc(val))
            out.append(f'<span class="hl-v">{_esc(m.group(1))}</span>={val_html}')
        else:
            out.append(_esc(ln))
    return "\n".join(out)


def highlight(code: str, lang: str) -> str:
    if lang == "bash":
        return _hl_bash(code)
    if lang == "json":
        return _hl_json(code)
    if lang == "env":
        return _hl_env(code)
    return _esc(code)


def convert(md: str) -> str:
    lines = md.splitlines()
    out, i = [], 0
    in_ul = in_ol = False

    def join_wrapped(parts: list[str]) -> str:
        """Join soft-wrapped Markdown without splitting hyphenated/path terms."""
        text = parts[0].strip()
        for part in parts[1:]:
            separator = "" if text.endswith(("-", "/")) else " "
            text += separator + part.strip()
        return text

    def close_lists():
        nonlocal in_ul, in_ol
        if in_ul:
            out.append("</ul>")
            in_ul = False
        if in_ol:
            out.append("</ol>")
            in_ol = False

    def list_item(pattern: str, line: str) -> str:
        """Consume one list item, including indented wrapped prose lines."""
        nonlocal i
        parts = [re.sub(pattern, "", line, count=1).strip()]
        while i + 1 < len(lines):
            following = lines[i + 1]
            if not following.strip() or not following[:1].isspace():
                break
            if re.match(r"^\s*(?:-|\d+\.)\s+", following):
                break
            if re.match(r"^\s*(?:#{1,4}\s|```|\|)", following):
                break
            i += 1
            parts.append(lines[i].strip())
        return join_wrapped(parts)

    while i < len(lines):
        line = lines[i]

        if line.startswith("```"):
            close_lists()
            lang = line[3:].strip()
            block = []
            i += 1
            while i < len(lines) and not lines[i].startswith("```"):
                block.append(lines[i])
                i += 1
            i += 1
            cls = f' class="lang-{lang}"' if lang else ""
            out.append(f"<pre><code{cls}>{highlight(chr(10).join(block), lang)}</code></pre>")
            continue

        if line.startswith("|") and i + 1 < len(lines) and re.match(r"^\|[\s:|-]+\|$", lines[i + 1]):
            close_lists()
            cells = [c.strip() for c in line.strip("|").split("|")]
            out.append("<table><thead><tr>" +
                       "".join(f"<th>{inline(c)}</th>" for c in cells) +
                       "</tr></thead><tbody>")
            i += 2
            while i < len(lines) and lines[i].startswith("|"):
                cells = [c.strip() for c in lines[i].strip("|").split("|")]
                out.append("<tr>" + "".join(f"<td>{inline(c)}</td>" for c in cells) + "</tr>")
                i += 1
            out.append("</tbody></table>")
            continue

        m = re.match(r"^(#{1,4})\s+(.*)$", line)
        if m:
            close_lists()
            level = len(m.group(1))
            text = m.group(2)
            out.append(f'<h{level} id="{slug(text)}">{inline(text)}</h{level}>')
            i += 1
            continue

        if re.match(r"^\s*-\s+", line):
            if not in_ul:
                close_lists()
                out.append("<ul>")
                in_ul = True
            out.append(f"<li>{inline(list_item(r'^\s*-\s+', line))}</li>")
            i += 1
            continue

        ordered = re.match(r"^\s*(\d+)\.\s+", line)
        if ordered:
            if not in_ol:
                close_lists()
                start = int(ordered.group(1))
                out.append("<ol>" if start == 1 else f'<ol start="{start}">')
                in_ol = True
            out.append(f"<li>{inline(list_item(r'^\s*\d+\.\s+', line))}</li>")
            i += 1
            continue

        if not line.strip():
            close_lists()
            i += 1
            continue

        close_lists()
        para = [line]
        while i + 1 < len(lines) and lines[i + 1].strip() and not re.match(
                r"^(#{1,4}\s|```|\||\s*-\s|\s*\d+\.\s)", lines[i + 1]):
            i += 1
            para.append(lines[i])
        out.append(f"<p>{inline(join_wrapped(para))}</p>")
        i += 1

    close_lists()
    return "\n".join(out)


def verify_converter() -> None:
    """Guard list continuation and explicit ordered-list starts."""
    rendered = convert(
        "11. Wrapped security-\n"
        "    boundary item\n"
        "12. Next item\n\n"
        "- Provider/\n"
        "  configuration\n"
    )
    assert '<ol start="11">' in rendered
    assert rendered.count("<ol") == 1
    assert "Wrapped security-boundary item" in rendered
    assert "<li>Next item</li>" in rendered
    assert "<li>Provider/configuration</li>" in rendered


