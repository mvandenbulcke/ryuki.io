    src = src_path or source_for(name)
    try:
        rel = src.relative_to(ROOT).as_posix()
    except ValueError:
        rel = ""  # source outside the repo (e.g. --api-doc override)
    date = ""
    if rel:
        date = subprocess.run(
            ["git", "log", "-1", "--format=%cs", "--", rel],
            capture_output=True, text=True, cwd=ROOT).stdout.strip()
    stamp = f"Last updated {date} · " if date else ""
    if note is None:
        note = GENERATED_NOTE.get(name)
    if note:
        return f'<div class="page-meta">{stamp}{note}</div>'
    edit = f"https://github.com/mvandenbulcke/ryuki.io/edit/main/{rel}"
    return (f'<div class="page-meta">{stamp}'
            f'<a href="{edit}" target="_blank" rel="noopener">Edit this page on GitHub</a></div>')


