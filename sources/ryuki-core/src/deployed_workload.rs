    #[test]
    fn rejects_unknown_duplicate_malformed_deep_and_oversized_json() {
        assert_invalid(verify_mutation(
            OciSubjectKind::OciImageManifest,
            |response| {
                response
                    .as_object_mut()
                    .expect("fixture object")
                    .insert("unexpected".to_owned(), json!(true));
            },
        ));

        let fixture = Fixture::new(OciSubjectKind::OciImageManifest);
        let request = fixture.request();
        let valid = String::from_utf8(fixture.response_with(&request, |_| {}))
            .expect("fixture response is UTF-8");
        let duplicate = format!(
            "{{\"schema_version\":\"{}\",{}",
            DEPLOYED_WORKLOAD_PROTOCOL_VERSION,
            &valid[1..]
        );
        assert_invalid(fixture.verify(request, duplicate.as_bytes()));

        let fixture = Fixture::new(OciSubjectKind::OciImageManifest);
        let request = fixture.request();
        let mut malformed: Value = serde_json::from_slice(&fixture.response_with(&request, |_| {}))
            .expect("fixture response parses");
        malformed["signature_base64"] = json!("not canonical base64");
        let malformed = serde_json::to_vec(&malformed).expect("malformed fixture serializes");
        assert_invalid(fixture.verify(request, &malformed));

        let fixture = Fixture::new(OciSubjectKind::OciImageManifest);
        let request = fixture.request();
        let mut deep = fixture.unsigned_response(&request);
        let mut nested = Value::Null;
        for _ in 0..=MAX_JSON_DEPTH {
            let mut object = Map::new();
            object.insert("next".to_owned(), nested);
            nested = Value::Object(object);
        }
        deep.as_object_mut()
            .expect("fixture object")
            .insert("nested".to_owned(), nested);
        let deep = serde_json::to_vec(&deep).expect("deep fixture serializes");
        assert_invalid(fixture.verify(request, &deep));

        let fixture = Fixture::new(OciSubjectKind::OciImageManifest);
        let request = fixture.request();
        assert_invalid(fixture.verify(
            request,
            &vec![b' '; MAX_DEPLOYED_WORKLOAD_RESPONSE_BYTES + 1],
        ));
    }

