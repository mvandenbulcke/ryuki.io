    pub fn workload_id(&self) -> &str {
        &self.namespace.workload_id
    }

    pub fn authority_id(&self) -> &str {
        &self.authority_id
    }

    pub fn authority_key_id(&self) -> &str {
        &self.authority_key_id
    }

    pub fn authority_public_key_fingerprint(&self) -> &str {
        &self.authority_public_key_fingerprint
    }

    pub fn authority_epoch(&self) -> u64 {
        self.authority_epoch
    }

    pub fn authority_revision(&self) -> u64 {
        self.authority_revision
    }

    pub fn measurement_profile_id(&self) -> &str {
        &self.measurement_profile.profile_id
    }

    pub fn measurement_profile_version(&self) -> u64 {
        self.measurement_profile.profile_version
    }

    pub fn measurement_profile_digest(&self) -> &str {
        &self.measurement_profile.content_digest
    }

    pub fn measurement_sequence(&self) -> u64 {
        self.measurement_sequence
    }

    pub fn oci_subject_kind(&self) -> OciSubjectKind {
        self.deployed_oci_subject.subject_kind
    }

    pub fn oci_repository(&self) -> &str {
        &self.deployed_oci_subject.repository
    }

    pub fn oci_subject_digest(&self) -> &str {
        &self.deployed_oci_subject.content_digest
    }

    pub fn resolved_manifest_digest(&self) -> &str {
        &self.resolved_image_manifest_digest
    }

